const BITS = {};
for (const [ch, rows] of Object.entries(GLYPHS)) BITS[ch] = rows.split(' ');

export const CHAR_W = 6;

export function textWidth(text, scale = 1) {
  return text.length * CHAR_W * scale - scale;
}

export function drawText(ctx, text, x, y, color, scale = 1, align = 'left') {
  text = text.toUpperCase();
  if (align === 'center') x = Math.round(x - textWidth(text, scale) / 2);
  else if (align === 'right') x = Math.round(x - textWidth(text, scale));
  ctx.fillStyle = color;
  for (let i = 0; i < text.length; i++) {
    const g = BITS[text[i]];
    if (!g) continue;
    const gx = x + i * CHAR_W * scale;
    for (let r = 0; r < 7; r++) {
      const row = g[r];
      for (let c = 0; c < 5; c++) {
        if (row[c] === '1') ctx.fillRect(gx + c * scale, y + r * scale, scale, scale);
      }
    }
  }
}
